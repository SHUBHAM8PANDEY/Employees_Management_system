const { readFileSync } = require('node:fs');
const { Client } = require('pg');
require('dotenv').config({ quiet: true });

const identifier = name => '"' + name + '"';
const quoteIdentifiers = sql => sql.replace(/`(\w+)`/g, (_, name) => identifier(name));

function compile(dump) {
    const tables = new Map();
    const inserts = [];
    const constraints = [];
    const seenIndexes = new Set();
    const escaped = { '0': '\0', b: '\b', n: '\n', r: '\r', t: '\t', Z: '\x1a' };
    const token = /'(?:\\[\s\S]|''|[^'\\])*'|^--[^\r\n]*|\/\*[\s\S]*?\*\/|;/gm;
    let start = 0;
    let statement = '';
    for (const match of dump.matchAll(token)) {
        statement += dump.slice(start, match.index);
        start = match.index + match[0].length;
        if (match[0].startsWith("'")) {
            const value = match[0].slice(1, -1)
                .replace(/\\([\s\S])|''/g, (_, char) => char === undefined ? "'" : (escaped[char] ?? char));
            if (value.includes('\0')) throw new Error('Dump contains a NUL in a string');
            statement += "'" + value.replaceAll("'", "''") + "'";
        } else if (match[0] === ';') {
            const sql = statement.trim();
            statement = '';
            let parts;
            if ((parts = /^CREATE TABLE `(\w+)` \(([\s\S]*)\) ENGINE=InnoDB\b/.exec(sql))) {
                const [, name, body] = parts;
                const columns = body.trim().split(/,\s*\r?\n/).map(line => {
                    const [, column, definition] = /^\s*`(\w+)` (.+)$/.exec(line);
                    const converted = definition
                        .replace(/^int\(\d+\)/, 'integer')
                        .replace(/^tinyint\(1\)/, 'boolean')
                        .replace(/^datetime/, 'timestamptz')
                        .replace(/^longtext/, 'text')
                        .replace(/^float/, 'double precision')
                        .replace(/^boolean(.* DEFAULT )([01])$/, (_, prefix, digit) => 'boolean' + prefix + (digit === '1'))
                        .replace(/current_timestamp\(\)/i, 'CURRENT_TIMESTAMP')
                        .replace(/ COMMENT '.*'$/, '')
                        .replace(/^enum\(([^)]+)\)(.*)$/, (_, values, rest) =>
                            'text' + rest + ' CHECK (' + identifier(column) + ' IN (' + values + '))');
                    return [column, converted];
                });
                tables.set(name, { columns, rowCount: 0 });
            } else if ((parts = /^INSERT INTO `(\w+)` \(([^)]+)\) VALUES\s+([\s\S]+)$/.exec(sql))) {
                const [, name, columnList, values] = parts;
                const table = tables.get(name);
                const columns = [...columnList.matchAll(/`(\w+)`/g)].map(match => match[1]);
                const columnTypes = new Map(table.columns);
                let index = 0;
                const valuesPattern = /'(?:''|[^'])*'|NULL|[-+]?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?|[(),]|\s+/gy;
                let position = 0;
                let converted = '';
                let value;
                while ((value = valuesPattern.exec(values))) {
                    position = valuesPattern.lastIndex;
                    const item = value[0];
                    if (item === '(') index = 0;
                    else if (item === ')') {
                        if (index !== columns.length) throw new Error('Unexpected row width in ' + name);
                        table.rowCount++;
                    } else if (item !== ',' && item.trim()) {
                        const type = columnTypes.get(columns[index++]);
                        if (!type) throw new Error('Unexpected column in ' + name);
                        if (type.startsWith('boolean') && /^[01]$/.test(item)) {
                            converted += item === '1' ? 'TRUE' : 'FALSE';
                            continue;
                        }
                    }
                    converted += item;
                }
                if (position !== values.length) throw new Error('Unsupported value in ' + name);
                inserts.push('INSERT INTO ' + identifier(name) + ' (' + quoteIdentifiers(columnList) + ') VALUES ' + converted);
            } else if ((parts = /^ALTER TABLE `(\w+)`\s+([\s\S]+)$/.exec(sql))) {
                const [, name, changes] = parts;
                const table = identifier(name);
                if ((parts = /^MODIFY `(\w+)` int\(\d+\) NOT NULL AUTO_INCREMENT, AUTO_INCREMENT=(\d+)$/.exec(changes))) {
                    const [, column, next] = parts;
                    constraints.push('ALTER TABLE ' + table + ' ALTER COLUMN ' + identifier(column)
                        + ' ADD GENERATED BY DEFAULT AS IDENTITY (START WITH ' + next + ')');
                    continue;
                }
                for (const change of changes.split(/,\s*\r?\n/)) {
                    const index = /^\s*ADD (UNIQUE )?KEY `(\w+)` (\([^)]+\))$/.exec(change);
                    if (index) {
                        const [, unique, label, columns] = index;
                        const key = [name, Boolean(unique), columns].join(':');
                        if (seenIndexes.has(key)) continue;
                        seenIndexes.add(key);
                        constraints.push('CREATE ' + (unique || '') + 'INDEX ' + identifier(name + '_' + label)
                            + ' ON ' + table + ' ' + quoteIdentifiers(columns));
                    } else if (/^\s*ADD (PRIMARY KEY|CONSTRAINT `\w+` FOREIGN KEY) /.test(change)) {
                        constraints.push('ALTER TABLE ' + table + ' ' + quoteIdentifiers(change.trim()));
                    } else {
                        throw new Error('Unsupported ALTER TABLE in ' + name);
                    }
                }
            } else if (sql && !/^(SET SQL_MODE = "NO_AUTO_VALUE_ON_ZERO"|SET time_zone = ["']\+00:00["']|START TRANSACTION|COMMIT)$/.test(sql)) {
                throw new Error('Unsupported statement in dump: ' + sql.split(/\s+/).slice(0, 2).join(' '));
            }
        }
    }
    if ((statement + dump.slice(start)).trim() || !tables.size) throw new Error('Incomplete dump');
    return { tables, inserts, constraints };
}

async function main() {
    const [path, option] = process.argv.slice(2);
    if (!path) throw new Error('Usage: npm run db:import -- <dump.sql> [--check]');
    const { tables, inserts, constraints } = compile(readFileSync(path, 'utf8'));
    if (option === '--check') {
        console.table(Object.fromEntries([...tables].map(([name, table]) => [name, table.rowCount])));
        return;
    }
    if (option) throw new Error('Unknown import option');
    if (!process.env.DATABASE_URL) throw new Error('DATABASE_URL is required');

    const url = new URL(process.env.DATABASE_URL);
    // Use a direct connection for transaction-scoped schema creation and validation.
    url.hostname = url.hostname.replace(/-pooler\./, '.');
    const client = new Client({
        host: url.hostname,
        port: Number(url.port || 5432),
        database: decodeURIComponent(url.pathname.slice(1)),
        user: decodeURIComponent(url.username),
        password: decodeURIComponent(url.password),
        ssl: { rejectUnauthorized: true },
        enableChannelBinding: url.searchParams.get('channel_binding') === 'require',
        connectionTimeoutMillis: 15000
    });
    await client.connect();
    try {
        await client.query('BEGIN');
        await client.query("SET LOCAL search_path TO public; SET LOCAL TIME ZONE 'UTC'; SET LOCAL standard_conforming_strings = on");
        for (const [name, { columns }] of tables) {
            await client.query('CREATE TABLE ' + identifier(name) + ' (' +
                columns.map(([column, definition]) => identifier(column) + ' ' + definition).join(', ') + ')');
        }
        for (const sql of [...inserts, ...constraints]) await client.query(sql);
        for (const [name, { rowCount }] of tables) {
            const { rows } = await client.query('SELECT count(*)::integer AS count FROM ' + identifier(name));
            if (rows[0].count !== rowCount) throw new Error('Row count mismatch in ' + name);
        }
        await client.query('COMMIT');
        console.table(Object.fromEntries([...tables].map(([name, table]) => [name, table.rowCount])));
    } catch (error) {
        await client.query('ROLLBACK');
        throw error;
    } finally {
        await client.end();
    }
}

main().catch(error => {
    // Driver details can contain source row values.
    console.error('Import failed:', error.code || error.message);
    if (error.table) console.error('Table:', error.table);
    if (error.constraint) console.error('Constraint:', error.constraint);
    process.exitCode = 1;
});

